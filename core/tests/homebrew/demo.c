/* FIFA STREET Recompiled - homebrew runtime test screen (original code, MIT).
 *
 * fsr_frame() is called by the host once per video frame with a guest
 * framebuffer (RGBA8 stored as big-endian 0xRRGGBBAA words). It polls the pad
 * through the real XAM import XamInputGetState and, on the first frame, reads
 * game:\data\hello.txt through the kernel file imports (served straight from
 * the ISO), then draws a resolution-independent test screen that states what
 * it is and shows exactly what the recompiled guest code received:
 *   - pressed buttons by name, stick and trigger values;
 *   - a ball moved by the left stick / D-pad, coloured by A/B/X/Y, sized by LT/RT;
 *   - the text read from the disc.
 */
#include <stdint.h>

typedef struct {
  uint32_t packet;
  uint16_t buttons;
  uint8_t lt, rt;
  int16_t lx, ly, rx, ry;
} XINPUT_STATE;
typedef struct { uint16_t length, max_length; uint32_t buffer; } ANSI_STRING;
typedef struct { uint32_t root_directory, object_name, attributes; } OBJECT_ATTRIBUTES;
typedef struct { uint32_t status, information; } IO_STATUS_BLOCK;

uint32_t XamInputGetState(uint32_t user, uint32_t flags, XINPUT_STATE* state);
uint32_t DbgPrint(const char* fmt, ...);
uint32_t NtOpenFile(uint32_t* handle, uint32_t access, OBJECT_ATTRIBUTES* oa, IO_STATUS_BLOCK* iosb, uint32_t options);
uint32_t NtReadFile(uint32_t handle, uint32_t event, uint32_t apc, uint32_t apc_ctx, IO_STATUS_BLOCK* iosb,
                    void* buffer, uint32_t length, uint64_t* offset);
uint32_t NtClose(uint32_t handle);

