/* Ball position as a fraction of the screen (0..65535) so it is resolution independent. */
static int32_t g_px = 16384, g_py = 26000;
static uint32_t g_color = 0xF0D23CFFu;
static int g_started;
static char g_disc[72];

void fsr_demo_reset(void) {
  g_px = 16384;
  g_py = 26000;
  g_color = 0xF0D23CFFu;
  g_started = 0;
  g_disc[0] = 0;
}

static inline void put(uint32_t* fb, int w, int h, int x, int y, uint32_t c) {
  if (x >= 0 && y >= 0 && x < w && y < h) fb[y * w + x] = c;
}

static void rect(uint32_t* fb, int w, int h, int x0, int y0, int rw, int rh, uint32_t c) {
  for (int y = y0; y < y0 + rh; y++)
    for (int x = x0; x < x0 + rw; x++) put(fb, w, h, x, y, c);
}

/* Draws text with a 1-pixel shadow; returns the x after the text. */
static int text(uint32_t* fb, int w, int h, int x, int y, int s, const char* t, uint32_t c) {
  for (; *t; t++) {
    int ch = *t;
    if (ch >= 'a' && ch <= 'z') ch -= 32;
    if (ch < 32 || ch > 95) ch = '?';
    const uint8_t* g = kFont[ch - 32];
    for (int r = 0; r < 7; r++)
      for (int k = 0; k < 5; k++)
        if (g[r] & (0x10 >> k)) {
          rect(fb, w, h, x + k * s + 1, y + r * s + 1, s, s, 0x000000FFu);
          rect(fb, w, h, x + k * s, y + r * s, s, s, c);
        }
    x += 6 * s;
  }
  return x;
}

static char* append(char* p, const char* s) { while (*s) *p++ = *s++; *p = 0; return p; }
static char* append_int(char* p, int32_t v) {
  char tmp[12];
  int n = 0;
  uint32_t u = v < 0 ? (uint32_t)-v : (uint32_t)v;
  do { tmp[n++] = (char)('0' + u % 10); u /= 10; } while (u);
  if (v < 0) *p++ = '-';
  while (n) *p++ = tmp[--n];
  *p = 0;
  return p;
}
static char* append_hex(char* p, uint32_t v) {
  for (int i = 7; i >= 0; i--) *p++ = "0123456789ABCDEF"[(v >> (4 * i)) & 15];
  *p = 0;
  return p;
}

static void read_disc_text(void) {
  static const char path[] = "game:\\data\\hello.txt";
  ANSI_STRING name;
  OBJECT_ATTRIBUTES oa;
  IO_STATUS_BLOCK iosb;
  uint32_t h = 0;
  name.length = sizeof(path) - 1;
  name.max_length = sizeof(path);
  name.buffer = (uint32_t)(uintptr_t)path;
  oa.root_directory = 0xFFFFFFFDu;
  oa.object_name = (uint32_t)(uintptr_t)&name;
  oa.attributes = 0x40;
  uint32_t st = NtOpenFile(&h, 0x80100000u, &oa, &iosb, 0x20);
  char* p = g_disc;
  if (st != 0) {
    p = append(p, "GAME:\\DATA\\HELLO.TXT TIDAK TERBACA (STATUS ");
    p = append_hex(p, st);
    append(p, ")");
    return;
  }
  char buf[44];
  uint32_t n = 0;
  if (NtReadFile(h, 0, 0, 0, &iosb, buf, sizeof buf, 0) == 0) n = iosb.information;
  NtClose(h);
  p = append(p, "GAME:\\DATA\\HELLO.TXT = \"");
  for (uint32_t i = 0; i < n && buf[i] != '\n' && buf[i] != '\r'; i++) *p++ = buf[i];
  append(p, "\"");
}

uint32_t fsr_frame(uint32_t* fb, int32_t w, int32_t h, uint32_t frame) {
  if (!g_started) {
    g_started = 1;
    read_disc_text();
    DbgPrint("homebrew demo running: %dx%d, disc: %s\n", w, h, g_disc);
  }
  XINPUT_STATE st;
  uint32_t buttons = 0;
  int32_t lx = 0, ly = 0, rx = 0, ry = 0, lt = 0, rt = 0;
  if (XamInputGetState(0, 0, &st) == 0) {
    buttons = st.buttons;
    lx = st.lx; ly = st.ly; rx = st.rx; ry = st.ry; lt = st.lt; rt = st.rt;
  }
  int32_t mx = lx, my = ly;
  if (buttons & 0x0004) mx = -24000;
  if (buttons & 0x0008) mx = 24000;
  if (buttons & 0x0001) my = 24000;
  if (buttons & 0x0002) my = -24000;
  if (mx > 3000 || mx < -3000) g_px += mx / 40;
  if (my > 3000 || my < -3000) g_py -= my * 16 / 9 / 40;
  if (g_px < 0) g_px = 0;
  if (g_py < 0) g_py = 0;
  if (g_px > 65535) g_px = 65535;
  if (g_py > 65535) g_py = 65535;
  if (buttons & 0x1000) g_color = 0x3CD25AFFu;  /* A green */
  if (buttons & 0x2000) g_color = 0xE63C3CFFu;  /* B red */
  if (buttons & 0x4000) g_color = 0x3C78F0FFu;  /* X blue */
  if (buttons & 0x8000) g_color = 0xF0D23CFFu;  /* Y yellow */

  int s = (h + 150) / 300; /* text/line scale: 180p->1, 480p/720p->2, 1080p->4 */
  if (s < 1) s = 1;
  /* Background: calm vertical gradient (street court at night). */
  for (int y = 0; y < h; y++) {
    uint32_t r = (uint32_t)(16 + 10 * y / h), g = (uint32_t)(30 + 46 * y / h), b = (uint32_t)(44 + 4 * y / h);
    uint32_t c = r << 24 | g << 16 | b << 8 | 0xFF;
    uint32_t* row = fb + y * w;
    for (int x = 0; x < w; x++) row[x] = c;
  }
  /* Court markings. */
  uint32_t line = 0xD8DEE4FFu;
  int m = 12 * s, top = 60 * s;
  rect(fb, w, h, m, top, w - 2 * m, s, line);
  rect(fb, w, h, m, h - m, w - 2 * m, s, line);
  rect(fb, w, h, m, top, s, h - m - top, line);
  rect(fb, w, h, w - m - s, top, s, h - m - top, line);
  rect(fb, w, h, w / 2, top, s, h - m - top, line);
  int cr = (h - m - top) / 5, ccx = w / 2, ccy = (top + h - m) / 2;
  for (int a = -cr; a <= cr; a++)
    for (int b = -cr; b <= cr; b++) {
      int d = a * a + b * b;
      if (d <= cr * cr && d >= (cr - s) * (cr - s)) put(fb, w, h, ccx + a, ccy + b, line);
    }
  /* Ball. */
  int area_w = w - 2 * m, area_h = h - m - top;
  int bx = m + (int)((int64_t)g_px * area_w / 65536), by = top + (int)((int64_t)g_py * area_h / 65536);
  int br = h / 30 + (lt + rt) * h / (255 * 30);
  for (int dy = -br; dy <= br; dy++)
    for (int dx = -br; dx <= br; dx++) {
      int d = dx * dx + dy * dy;
      if (d > br * br) continue;
      uint32_t c = d >= (br - s - 1) * (br - s - 1) ? 0x101010FFu : ((((dx + br) / (br / 2 + 1)) + ((dy + br) / (br / 2 + 1))) & 1 ? g_color : 0xF4F4F4FFu);
      put(fb, w, h, bx + dx, by + dy, c);
    }

  /* Text panel. */
  int x0 = 8 * s, y = 6 * s, lh = 9 * s;
  rect(fb, w, h, 0, 0, w, top - 2 * s, 0x0A0F18FFu);
  text(fb, w, h, x0, y, s, "UJI RUNTIME (HOMEBREW) - BUKAN GAME FIFA STREET", 0xFFD24AFFu);
  y += lh;
  text(fb, w, h, x0, y, s, "KODE POWERPC -> ARM64 NATIVE, LAYAR VIA VULKAN", 0xE8EDF5FFu);
  y += lh;
  char tmp[160];
  char* p = append(tmp, "DISC: ");
  append(p, g_disc);
  text(fb, w, h, x0, y, s, tmp, 0x9FE0A8FFu);
  y += lh;
  static const char* names[16] = {"UP", "DOWN", "LEFT", "RIGHT", "START", "BACK", "LS", "RS",
                                  "LB", "RB", "?", "?", "A", "B", "X", "Y"};
  p = append(tmp, "TOMBOL:");
  int any = 0;
  for (int i = 0; i < 16; i++)
    if (buttons & (1u << i)) { p = append(p, " "); p = append(p, names[i]); any = 1; }
  if (lt) { p = append(p, " LT="); p = append_int(p, lt); any = 1; }
  if (rt) { p = append(p, " RT="); p = append_int(p, rt); any = 1; }
  if (!any) append(p, " (TIDAK ADA)");
  text(fb, w, h, x0, y, s, tmp, 0xFFFFFFFFu);
  y += lh;
  p = append(tmp, "ANALOG L ");
  p = append_int(p, lx); p = append(p, ","); p = append_int(p, ly);
  p = append(p, "   R "); p = append_int(p, rx); p = append(p, ","); p = append_int(p, ry);
  p = append(p, "   FRAME "); append_int(p, (int32_t)frame);
  text(fb, w, h, x0, y, s, tmp, 0xB8C4D6FFu);
  /* Hint at the bottom-left of the court. */
  text(fb, w, h, m + 4 * s, h - m - 10 * s, s, "BOLA: ANALOG KIRI/D-PAD  WARNA: A/B/X/Y  UKURAN: LT/RT", 0xB8C4D6FFu);
  return buttons;
}
